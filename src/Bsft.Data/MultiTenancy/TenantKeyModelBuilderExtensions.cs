using System.Linq.Expressions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Bsft.Data.MultiTenancy;

/// <summary>
/// The one switch that maps the framework's own tables tenant-keyed, and the pieces their mappings are
/// built from.
/// </summary>
/// <remarks>
/// <para>
/// A host calls <see cref="UseTenantKeys"/> once in <c>OnModelCreating</c> of every context that holds
/// framework tables, before it applies their configurations. Every configuration of the audit,
/// idempotency, messaging, workflow and feature flag packages then maps its table with a non-null <c>TenantId</c>
/// and, where the table had an identity column, the key <c>(TenantId, Id)</c> with an <c>Id</c> the
/// client creates. Without the call every table keeps the schema it had.
/// </para>
/// <para>
/// The host also calls <c>AddBsftDataTenantKeys</c>, which is required with this switch: it registers the
/// node id of the ids and the start check of the context registrations. A multi-tenancy host that maps
/// tenant keys without it fails at start.
/// </para>
/// <para>
/// The stores read the decision back from the model (<see cref="IsTenantKeyed(IReadOnlyEntityType)"/>),
/// so the code that writes and queries a table cannot disagree with the schema it was mapped to.
/// </para>
/// </remarks>
public static class TenantKeyModelBuilderExtensions
{
    /// <summary>
    /// Maps every framework table this model holds tenant-keyed.
    /// </summary>
    /// <param name="modelBuilder">The model builder.</param>
    /// <returns>The same model builder.</returns>
    /// <exception cref="ArgumentNullException">Thrown when <paramref name="modelBuilder"/> is null.</exception>
    /// <exception cref="InvalidOperationException">
    /// Thrown when a framework configuration was applied before this call; its table would otherwise keep
    /// the schema without tenant keys and nothing would say so.
    /// </exception>
    public static ModelBuilder UseTenantKeys(this ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);

        var early = modelBuilder.Model.GetEntityTypes()
            .Where(entityType => entityType.FindAnnotation(TenantKeys.TenantKeyableAnnotation) is not null)
            .Select(entityType => entityType.DisplayName())
            .ToList();

        if (early.Count > 0)
        {
            throw new InvalidOperationException(
                "UseTenantKeys must be called before the framework entity configurations are applied, but these were "
                + $"already configured without tenant keys: {string.Join(", ", early)}.");
        }

        modelBuilder.HasAnnotation(TenantKeys.TenantKeyedAnnotation, true);

        return modelBuilder;
    }

    /// <summary>
    /// Answers, inside an entity configuration, whether the model maps the framework tables
    /// tenant-keyed, and records that this entity's mapping depends on the answer.
    /// </summary>
    /// <param name="builder">The entity type builder.</param>
    /// <returns><see langword="true"/> when <see cref="UseTenantKeys"/> was called on the model.</returns>
    /// <exception cref="ArgumentNullException">Thrown when <paramref name="builder"/> is null.</exception>
    /// <remarks>
    /// The record is what lets a <see cref="UseTenantKeys"/> written after the configurations fail rather
    /// than leave the tables behind.
    /// </remarks>
    public static bool IsTenantKeyed(this EntityTypeBuilder builder)
    {
        ArgumentNullException.ThrowIfNull(builder);

        builder.HasAnnotation(TenantKeys.TenantKeyableAnnotation, true);

        return builder.Metadata.Model.FindAnnotation(TenantKeys.TenantKeyedAnnotation)?.Value is true;
    }

    /// <summary>
    /// Maps the key <c>(TenantId, Id)</c>: a required tenant filled from the scope and an <c>Id</c>
    /// from the time-ordered generator, neither generated by the database.
    /// </summary>
    /// <typeparam name="TEntity">The entity type.</typeparam>
    /// <param name="builder">The entity type builder.</param>
    /// <param name="tenantId">The tenant property.</param>
    /// <param name="id">The 64-bit id property.</param>
    /// <returns>The same builder.</returns>
    /// <exception cref="ArgumentNullException">Thrown when an argument is null.</exception>
    public static EntityTypeBuilder<TEntity> HasTenantKey<TEntity>(
        this EntityTypeBuilder<TEntity> builder,
        Expression<Func<TEntity, string?>> tenantId,
        Expression<Func<TEntity, long>> id)
        where TEntity : class
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentNullException.ThrowIfNull(tenantId);
        ArgumentNullException.ThrowIfNull(id);

        builder.HasRequiredTenantId(tenantId);

        // Never generated by the store, so no provider turns the column into an identity or a
        // sequence; the value generator fills it on Add, before the row reaches the database.
        builder.Property(id).ValueGeneratedNever().HasValueGenerator<TimeOrderedIdValueGenerator>();
        builder.HasKey(MemberName(tenantId), MemberName(id));

        return builder;
    }

    /// <summary>
    /// Maps a required tenant column of <see cref="TenantKeys.TenantIdMaxLength"/>, filled from the
    /// scope when the writer left it empty. A table whose key is a Guid needs nothing more.
    /// </summary>
    /// <typeparam name="TEntity">The entity type.</typeparam>
    /// <param name="builder">The entity type builder.</param>
    /// <param name="tenantId">The tenant property.</param>
    /// <returns>The same builder.</returns>
    /// <exception cref="ArgumentNullException">Thrown when an argument is null.</exception>
    public static EntityTypeBuilder<TEntity> HasRequiredTenantId<TEntity>(
        this EntityTypeBuilder<TEntity> builder, Expression<Func<TEntity, string?>> tenantId)
        where TEntity : class
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentNullException.ThrowIfNull(tenantId);

        builder.Property(tenantId)
            .IsRequired()
            .HasMaxLength(TenantKeys.TenantIdMaxLength)
            .ValueGeneratedNever()
            .HasValueGenerator<CurrentTenantIdValueGenerator>();

        return builder;
    }

    /// <summary>
    /// Answers, at run time, whether an entity type is mapped tenant-keyed: whether it has a
    /// non-nullable <c>TenantId</c> column.
    /// </summary>
    /// <param name="entityType">The entity type, or <see langword="null"/>.</param>
    /// <returns><see langword="true"/> for a tenant-keyed mapping.</returns>
    /// <remarks>
    /// Read from the mapped column rather than from an annotation, so the answer is what the schema
    /// says, however the model was built.
    /// </remarks>
    public static bool IsTenantKeyed(this IReadOnlyEntityType? entityType) =>
        entityType?.FindProperty(TenantKeys.TenantIdColumnName) is { IsNullable: false };

    /// <summary>Answers, at run time, whether the entity type behind a set is mapped tenant-keyed.</summary>
    /// <typeparam name="TEntity">The entity type.</typeparam>
    /// <param name="set">The set.</param>
    /// <returns><see langword="true"/> for a tenant-keyed mapping.</returns>
    /// <exception cref="ArgumentNullException">Thrown when <paramref name="set"/> is null.</exception>
    public static bool IsTenantKeyed<TEntity>(this DbSet<TEntity> set)
        where TEntity : class
    {
        ArgumentNullException.ThrowIfNull(set);

        return set.EntityType.IsTenantKeyed();
    }

    private static string MemberName(LambdaExpression expression) =>
        expression.Body is MemberExpression member
            ? member.Member.Name
            : throw new ArgumentException("The expression must name a property, as in e => e.Id.", nameof(expression));
}
