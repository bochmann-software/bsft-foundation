using Bsft.Messaging.EFCore.Tests.Support;
using FluentAssertions;
using Microsoft.EntityFrameworkCore;
using Xunit;

namespace Bsft.Messaging.EFCore.Tests;

/// <summary>
/// The PostgreSQL create script of <c>OutboxMessages</c> and <c>InboxMessages</c>, per table, with and
/// without <c>UseTenantKeys</c>. The script is generated from the model, so no server is needed.
/// </summary>
public sealed class MessagingSchemaTenantKeyTests
{
    private static string KeyedScript()
    {
        using var db = new TestTenantKeyedDbContext(
            new DbContextOptionsBuilder<TestTenantKeyedDbContext>().UseNpgsql("Host=localhost").Options);
        return db.Database.GenerateCreateScript();
    }

    private static string PlainScript()
    {
        using var db = new TestPostgresDbContext(
            new DbContextOptionsBuilder<TestPostgresDbContext>().UseNpgsql("Host=localhost").Options);
        return db.Database.GenerateCreateScript();
    }

    [Theory]
    [InlineData("OutboxMessages")]
    [InlineData("InboxMessages")]
    public void GenerateCreateScript_WithTenantKeys_TableHasRequiredTenantAndCompositeKeyWithoutIdentity(string table)
    {
        var sql = CreateScript.Table(KeyedScript(), table);

        sql.Should().Contain("\"TenantId\" character varying(128) NOT NULL");
        sql.Should().Contain($"CONSTRAINT \"PK_{table}\" PRIMARY KEY (\"TenantId\", \"Id\")");
        sql.Should().Contain("\"Id\" bigint NOT NULL");
        sql.Should().NotContain("IDENTITY").And.NotContain("GENERATED");
    }

    [Theory]
    [InlineData("OutboxMessages")]
    [InlineData("InboxMessages")]
    public void GenerateCreateScript_WithoutTenantKeys_TableKeepsIdentityAndHasNoTenant(string table)
    {
        var sql = CreateScript.Table(PlainScript(), table);

        sql.Should().Contain("GENERATED BY DEFAULT AS IDENTITY");
        sql.Should().Contain($"CONSTRAINT \"PK_{table}\" PRIMARY KEY (\"Id\")");
        sql.Should().NotContain("\"TenantId\"");
    }

    [Fact]
    public void GenerateCreateScript_WithTenantKeys_InboxIsUniquePerTenant()
    {
        KeyedScript().Should().Contain(
            "CREATE UNIQUE INDEX \"IX_InboxMessages_TenantId_Consumer_EventId\" ON \"InboxMessages\" (\"TenantId\", \"Consumer\", \"EventId\");");
        PlainScript().Should().Contain(
            "CREATE UNIQUE INDEX \"IX_InboxMessages_Consumer_EventId\" ON \"InboxMessages\" (\"Consumer\", \"EventId\");");
    }
}
