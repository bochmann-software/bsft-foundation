using Bsft.Idempotency.EFCore.Tests.Support;
using FluentAssertions;
using Microsoft.EntityFrameworkCore;
using Xunit;

namespace Bsft.Idempotency.EFCore.Tests;

/// <summary>
/// Verifies that the generated SQL schema on PostgreSQL includes TenantId columns and indexes
/// correctly when tenant keys are enabled via UseTenantKeys(). Tests GenerateCreateScript without a database.
/// </summary>
public sealed class IdempotencyRecordEntityConfigurationTenantKeyPostgresTests
{
    private readonly DbContextOptions<TenantKeyedTestIdempotencyDbContext> _keyedOptions;
    private readonly DbContextOptions<PostgresTestIdempotencyDbContext> _unkeyedOptions;

    public IdempotencyRecordEntityConfigurationTenantKeyPostgresTests()
    {
        // GenerateCreateScript does not require a real database connection
        _keyedOptions = new DbContextOptionsBuilder<TenantKeyedTestIdempotencyDbContext>()
            .UseNpgsql("Host=localhost")
            .Options;

        _unkeyedOptions = new DbContextOptionsBuilder<PostgresTestIdempotencyDbContext>()
            .UseNpgsql("Host=localhost")
            .Options;
    }

    [Fact]
    public void WithTenantKeys_IdempotencyRecordsTableHasTenantIdColumnNotNull()
    {
        using var context = new TenantKeyedTestIdempotencyDbContext(_keyedOptions);
        var script = context.Database.GenerateCreateScript();
        var tableScript = CreateScript.Table(script, "IdempotencyRecords");

        tableScript.Should().Contain("\"TenantId\" character varying(128) NOT NULL");
    }

    [Fact]
    public void WithTenantKeys_IdempotencyRecordsTableHasCompositePrimaryKey()
    {
        using var context = new TenantKeyedTestIdempotencyDbContext(_keyedOptions);
        var script = context.Database.GenerateCreateScript();
        var tableScript = CreateScript.Table(script, "IdempotencyRecords");

        // Primary key should be composite (TenantId, Id), not on Id alone
        tableScript.Should().Contain("CONSTRAINT \"PK_IdempotencyRecords\" PRIMARY KEY (\"TenantId\", \"Id\")");
    }

    [Fact]
    public void WithTenantKeys_IdempotencyRecordsTableHasNoIdentityOrGenerated()
    {
        using var context = new TenantKeyedTestIdempotencyDbContext(_keyedOptions);
        var script = context.Database.GenerateCreateScript();
        var tableScript = CreateScript.Table(script, "IdempotencyRecords");

        // With tenant keys, the Id is client-generated, not identity or GENERATED BY DEFAULT AS IDENTITY
        tableScript.Should().NotContain("IDENTITY");
        tableScript.Should().NotContain("GENERATED");
    }

    [Fact]
    public void WithTenantKeys_IdempotencyRecordsTableHasUniqueIndexOnTenantIdScopeKey()
    {
        using var context = new TenantKeyedTestIdempotencyDbContext(_keyedOptions);
        var script = context.Database.GenerateCreateScript();

        // Unique index on (TenantId, Scope, Key) to prevent collision across tenants.
        script.Should().Contain("CREATE UNIQUE INDEX");
        script.Should().Match("*\"TenantId\", \"Scope\", \"Key\"*");
    }

    [Fact]
    public void WithTenantKeys_IdempotencyRecordsTableHasIndexOnTenantIdExpiresAt()
    {
        using var context = new TenantKeyedTestIdempotencyDbContext(_keyedOptions);
        var script = context.Database.GenerateCreateScript();

        // Index on (TenantId, ExpiresAt) for efficient sweeper queries within a tenant.
        script.Should().Contain("CREATE INDEX");
        script.Should().Match("*\"TenantId\", \"ExpiresAt\"*");
    }

    [Fact]
    public void WithoutTenantKeys_IdempotencyRecordsTableHasNoTenantIdColumn()
    {
        using var context = new PostgresTestIdempotencyDbContext(_unkeyedOptions);
        var script = context.Database.GenerateCreateScript();
        var tableScript = CreateScript.Table(script, "IdempotencyRecords");

        // Without tenant keys, TenantId property is ignored, so the column should not exist.
        tableScript.Should().NotContain("\"TenantId\"");
    }

    [Fact]
    public void WithoutTenantKeys_IdempotencyRecordsTableHasIdentityPrimaryKey()
    {
        using var context = new PostgresTestIdempotencyDbContext(_unkeyedOptions);
        var script = context.Database.GenerateCreateScript();
        var tableScript = CreateScript.Table(script, "IdempotencyRecords");

        // Without tenant keys, the table uses identity: "Id" is GENERATED BY DEFAULT AS IDENTITY.
        tableScript.Should().Match("*\"Id\"*GENERATED BY DEFAULT AS IDENTITY*");
    }

    [Fact]
    public void WithoutTenantKeys_IdempotencyRecordsTableHasUniqueIndexOnScopeKey()
    {
        using var context = new PostgresTestIdempotencyDbContext(_unkeyedOptions);
        var script = context.Database.GenerateCreateScript();

        // Unique index on (Scope, Key) only, without TenantId.
        script.Should().Contain("CREATE UNIQUE INDEX");
        script.Should().Match("*\"Scope\", \"Key\"*");
        // Ensure that the unique index does not have TenantId as a leading column
        script.Should().Match("*IX_IdempotencyRecords_Scope_Key*");
    }

    [Fact]
    public void WithoutTenantKeys_IdempotencyRecordsTableHasIndexOnExpiresAtOnly()
    {
        using var context = new PostgresTestIdempotencyDbContext(_unkeyedOptions);
        var script = context.Database.GenerateCreateScript();

        // Index on ExpiresAt only, without TenantId.
        script.Should().Contain("CREATE INDEX");
        script.Should().Match("*\"ExpiresAt\"*");
        // Ensure that the index is on ExpiresAt alone
        script.Should().Match("*IX_IdempotencyRecords_ExpiresAt*");
    }
}
